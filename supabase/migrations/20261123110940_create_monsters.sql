-- =========================================================
-- スキル・モンスター図鑑（マスタデータ）と、プレイヤーの所持モンスター
-- テーブル名はダッシュボードで作成した名前（大文字を含む）に合わせている。
-- SQL で参照するときは "Monster_Species" のようにダブルクォートが必要。
-- =========================================================

-- ---------------------------------------------------------
-- スキル（マスタ）: Table Editor でデータを入力する
-- ---------------------------------------------------------
create table public."Skills" (
  id bigint generated by default as identity primary key,
  name text,
  description text
);

-- ---------------------------------------------------------
-- モンスター図鑑（マスタ）: Table Editor でデータを入力する
-- ---------------------------------------------------------
create table public."Monster_Species" (
  id bigint generated by default as identity primary key,
  name text not null,
  rank text,
  description text,
  -- Storage の Images バケット内のパス（例: "monsters/slime.png"）
  image_path text,
  -- パーティ編成の制限に使う予定のサイズ（ルールは別途決定）
  size bigint,
  hp bigint,
  atk bigint,
  def bigint,
  int bigint,
  spd bigint,
  -- 覚えるスキル（Skills.id）。Table Editor ではプルダウンで選べる
  skill_1 bigint references public."Skills" (id) on delete set null,
  skill_2 bigint references public."Skills" (id) on delete set null,
  skill_3 bigint references public."Skills" (id) on delete set null,
  skill_4 bigint references public."Skills" (id) on delete set null,
  skill_5 bigint references public."Skills" (id) on delete set null
);

-- マスタはログインユーザーなら誰でも読める。書き込みポリシーは作らない（ダッシュボードからのみ編集）
alter table public."Skills" enable row level security;
create policy "ログインユーザーはスキルを読める"
  on public."Skills" for select to authenticated using (true);

alter table public."Monster_Species" enable row level security;
create policy "ログインユーザーは図鑑を読める"
  on public."Monster_Species" for select to authenticated using (true);

-- ---------------------------------------------------------
-- 控えの上限: プロフィールに持たせる（デフォルト 100）
-- ---------------------------------------------------------
alter table public.profiles
  add column box_capacity int not null default 100 check (box_capacity >= 0);

-- プレイヤーが自分で box_capacity を書き換えられないよう、
-- 更新できる列を display_name だけに絞る（上限の拡張はアイテム使用の処理で行う）
revoke update on public.profiles from authenticated, anon;
grant update (display_name, updated_at) on public.profiles to authenticated;

-- ---------------------------------------------------------
-- 所持モンスター（1 行 = プレイヤーが持つ 1 体）
--   party_slot 1〜4 : バトルメンバー
--   party_slot 5〜8 : スタンバイメンバー
--   party_slot NULL : 控え（ボックス）
-- ---------------------------------------------------------
create table public."Player_Monsters" (
  id uuid primary key default gen_random_uuid(),
  owner_id uuid not null references auth.users (id) on delete cascade,
  species_id bigint not null references public."Monster_Species" (id),
  nickname text,
  level int not null default 1 check (level >= 1),
  exp bigint not null default 0 check (exp >= 0),
  party_slot bigint check (party_slot between 1 and 8),
  -- 個体ごとのステータス（成長で図鑑の値から変化する）。hp は最大 HP
  hp bigint,
  atk bigint,
  def bigint,
  int bigint,
  spd bigint,
  -- 個体が覚えているスキル（Skills.id）
  skill_1 bigint references public."Skills" (id) on delete set null,
  skill_2 bigint references public."Skills" (id) on delete set null,
  skill_3 bigint references public."Skills" (id) on delete set null,
  skill_4 bigint references public."Skills" (id) on delete set null,
  skill_5 bigint references public."Skills" (id) on delete set null,
  obtained_at timestamptz not null default now(),
  -- 同じプレイヤー内で枠番号の重複を禁止（NULL = 控えは何体でも可）。
  -- 入れ替え時に一時的に重複するので、チェックはトランザクション終了時まで遅らせる
  constraint "Player_Monsters_owner_slot_unique"
    unique (owner_id, party_slot) deferrable initially deferred
);

create index "Player_Monsters_owner_idx" on public."Player_Monsters" (owner_id);

alter table public."Player_Monsters" enable row level security;

-- 自分のモンスターだけ読める。変更は下の関数経由のみ（直接の insert/update/delete は不可）
create policy "自分の所持モンスターを読める"
  on public."Player_Monsters" for select
  to authenticated
  using (auth.uid() = owner_id);

-- ---------------------------------------------------------
-- 控えの上限チェック（控えに入る行が上限を超えたらエラー）
-- ---------------------------------------------------------
create function public.check_box_capacity()
returns trigger
language plpgsql
security definer set search_path = ''
as $$
declare
  capacity int;
  box_count int;
begin
  if new.party_slot is not null then
    return new;
  end if;
  if tg_op = 'UPDATE' and old.party_slot is null and old.owner_id = new.owner_id then
    return new; -- もともと控えにいた行の更新（レベルアップ等）は対象外
  end if;

  -- 同時実行で上限をすり抜けないよう、プロフィール行をロックする
  select p.box_capacity into capacity
    from public.profiles p
   where p.id = new.owner_id
   for update;

  select count(*) into box_count
    from public."Player_Monsters" m
   where m.owner_id = new.owner_id
     and m.party_slot is null
     and m.id <> new.id;

  if box_count >= capacity then
    raise exception '控えがいっぱいです（上限 % 体）', capacity
      using errcode = 'P0001';
  end if;
  return new;
end;
$$;

create trigger "Player_Monsters_box_capacity"
  before insert or update of party_slot, owner_id on public."Player_Monsters"
  for each row execute function public.check_box_capacity();

-- ---------------------------------------------------------
-- 編成の移動・入れ替え
--   target_slot に 1〜8 を指定 → その枠へ移動。先客がいれば元の場所と入れ替え
--   target_slot に NULL を指定 → 控えへ移動
-- アプリからは supabase.rpc('move_monster', { p_monster_id, p_target_slot }) で呼ぶ
-- ---------------------------------------------------------
create function public.move_monster(p_monster_id uuid, p_target_slot bigint)
returns void
language plpgsql
security definer set search_path = ''
as $$
declare
  uid uuid := auth.uid();
  from_slot bigint;
  occupant_id uuid;
begin
  if uid is null then
    raise exception 'ログインが必要です';
  end if;
  if p_target_slot is not null and p_target_slot not between 1 and 8 then
    raise exception '枠番号が不正です: %', p_target_slot;
  end if;

  select m.party_slot into from_slot
    from public."Player_Monsters" m
   where m.id = p_monster_id and m.owner_id = uid
   for update;
  if not found then
    raise exception 'モンスターが見つかりません';
  end if;

  if from_slot is not distinct from p_target_slot then
    return; -- 移動なし
  end if;

  if p_target_slot is not null then
    select m.id into occupant_id
      from public."Player_Monsters" m
     where m.owner_id = uid and m.party_slot = p_target_slot
     for update;
  end if;

  -- 先に移動する側を更新し、その後で先客を元の場所へ（控えの上限チェックを正しく行うため）
  update public."Player_Monsters" set party_slot = p_target_slot where id = p_monster_id;
  if occupant_id is not null then
    update public."Player_Monsters" set party_slot = from_slot where id = occupant_id;
  end if;
end;
$$;

revoke execute on function public.move_monster(uuid, bigint) from public, anon;
grant execute on function public.move_monster(uuid, bigint) to authenticated;

-- トリガー用関数はアプリから直接呼べないようにする
revoke execute on function public.check_box_capacity() from public, anon, authenticated;

