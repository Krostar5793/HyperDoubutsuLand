-- =========================================================
-- 合成
--   ・Lv10 以上の 2 体を合成すると、2 体はいなくなり、Lv1 の子が生まれる
--   ・子の候補: 属性が親のどちらかと同じ（属性なしの親がいれば属性なしも）、ランクが親の低い方とちょうど同じ
--   ・親が同ランクでレベル合計が基準（Ranks.fusion_rankup_level_sum）以上なら、1 つ上のランクも候補
--   ・特別な組み合わせ（Fusion_Recipes）なら、その子も候補
--   ・子の特技は両親の特技から選ぶ（特技の使用枠の合計が、子の枠の数まで）
--   ・成長ボーナス・LP ボーナスはサーバーの TypeScript（src/lib/game/fusion.ts）で計算する
-- =========================================================

-- ---------------------------------------------------------
-- 特技の使用枠（強い特技は 2 枠以上にできる）
-- ---------------------------------------------------------
alter table public."Skills"
  add column slot_cost int not null default 1 check (slot_cost between 1 and 20);

-- 枠のチェックを「使用枠の合計が枠の数まで」に変える
-- （Species_Skills / Monster_Skills の slot 列は、並び順の番号として使う）
create or replace function public.check_skill_slot()
returns trigger
language plpgsql
set search_path = ''
as $$
declare
  species bigint;
  slots int;
  used int;
  cost int;
begin
  select s.slot_cost into cost from public."Skills" s where s.id = new.skill_id;

  if tg_table_name = 'Species_Skills' then
    species := new.species_id;
    select coalesce(sum(s.slot_cost), 0) into used
      from public."Species_Skills" x join public."Skills" s on s.id = x.skill_id
     where x.species_id = new.species_id
       and not (tg_op = 'UPDATE' and x.species_id = old.species_id and x.slot = old.slot);
  else
    select m.species_id into species from public."Player_Monsters" m where m.id = new.monster_id;
    select coalesce(sum(s.slot_cost), 0) into used
      from public."Monster_Skills" x join public."Skills" s on s.id = x.skill_id
     where x.monster_id = new.monster_id
       and not (tg_op = 'UPDATE' and x.monster_id = old.monster_id and x.slot = old.slot);
  end if;

  slots := public.skill_slots_for_species(species);
  if used + cost > slots then
    raise exception '特技の枠が足りません（使用 % / 枠 %）', used + cost, slots;
  end if;
  return new;
end;
$$;

-- ---------------------------------------------------------
-- 図鑑: 通常の合成で生まれるか（特別な組み合わせ専用・イベント限定などは false にする）
-- ---------------------------------------------------------
alter table public."Monster_Species"
  add column fusion_selectable boolean not null default true;

-- 特別な組み合わせ（親の順番は問わない）
create table public."Fusion_Recipes" (
  id bigint generated by default as identity primary key,
  parent_a_species_id bigint not null references public."Monster_Species" (id) on delete cascade,
  parent_b_species_id bigint not null references public."Monster_Species" (id) on delete cascade,
  child_species_id bigint not null references public."Monster_Species" (id) on delete cascade,
  note text
);
create unique index "Fusion_Recipes_unique" on public."Fusion_Recipes" (
  least(parent_a_species_id, parent_b_species_id),
  greatest(parent_a_species_id, parent_b_species_id),
  child_species_id
);

alter table public."Fusion_Recipes" enable row level security;
create policy "ログインユーザーは合成の組み合わせを読める"
  on public."Fusion_Recipes" for select to authenticated using (true);
grant select on public."Fusion_Recipes" to authenticated;
grant all on public."Fusion_Recipes" to service_role;

-- ---------------------------------------------------------
-- ランクごとの合成の設定
--   fusion_rankup_level_sum: このランクの親どうしで、1 つ上のランクに上がるのに必要なレベル合計（なければ上がれない）
--   fusion_item_id / fusion_item_quantity: このランクの子を作るのに必要なアイテム（なければ無料）
-- ---------------------------------------------------------
alter table public."Ranks"
  add column fusion_rankup_level_sum int check (fusion_rankup_level_sum > 0),
  add column fusion_item_id bigint references public."Items" (id) on delete set null,
  add column fusion_item_quantity int not null default 1 check (fusion_item_quantity >= 1);

update public."Ranks" set fusion_rankup_level_sum = case code
  when 'E' then 50 when 'D' then 60 when 'C' then 70 when 'B' then 80 when 'A' then 90 when 'S' then 100
end;

-- ---------------------------------------------------------
-- 個体のボーナス（合成で付く。親からは引き継がない）
--   growth_bonus: { "atk": 0.2 } → atk の Lv50 までの成長量が 2 割増
--   stat_bonus  : { "atk": 9 }   → atk に +9
-- ---------------------------------------------------------
alter table public."Player_Monsters"
  add column growth_bonus jsonb not null default '{}'::jsonb,
  add column stat_bonus jsonb not null default '{}'::jsonb;

-- ---------------------------------------------------------
-- 合成を行う（サーバー側専用。候補やボーナスは TypeScript で検証・計算してから呼ぶ）
--   p_skill_ids: 子の特技（並び順）。枠のチェックはトリガーで行う
-- 戻り値: 子の monster_id と、預り所に入ったか
-- ---------------------------------------------------------
create function public.fuse_monsters(
  p_owner_id uuid,
  p_parent_a uuid,
  p_parent_b uuid,
  p_child_species_id bigint,
  p_skill_ids bigint[],
  p_growth_bonus jsonb,
  p_stat_bonus jsonb,
  p_item_id bigint default null,
  p_item_quantity int default 1
)
returns table (monster_id uuid, in_storage boolean)
language plpgsql
security definer set search_path = ''
as $$
declare
  n int;
  child record;
  i int;
begin
  if p_parent_a = p_parent_b then
    raise exception '同じモンスターどうしは合成できません';
  end if;
  if exists (select 1 from public."Expeditions" e where e.owner_id = p_owner_id and e.status = 'exploring') then
    raise exception '探索中は合成できません';
  end if;

  select count(*) into n
    from public."Player_Monsters" m
   where m.id in (p_parent_a, p_parent_b) and m.owner_id = p_owner_id and m.level >= 10;
  if n <> 2 then
    raise exception '合成できるのは、自分の Lv10 以上のモンスター 2 体です';
  end if;
  perform 1 from public."Player_Monsters" m where m.id in (p_parent_a, p_parent_b) for update;

  if p_item_id is not null then
    perform public.consume_item(p_owner_id, p_item_id, p_item_quantity);
  end if;

  delete from public."Player_Monsters" where id in (p_parent_a, p_parent_b);

  select * into child from public.grant_monster(p_owner_id, p_child_species_id, 1, 'fusion');

  update public."Player_Monsters"
     set growth_bonus = coalesce(p_growth_bonus, '{}'::jsonb),
         stat_bonus = coalesce(p_stat_bonus, '{}'::jsonb)
   where id = child.monster_id;

  -- 特技（1 つでもあれば、図鑑の特技より優先される）
  if p_skill_ids is not null then
    for i in 1 .. coalesce(array_length(p_skill_ids, 1), 0) loop
      insert into public."Monster_Skills" (monster_id, slot, skill_id)
      values (child.monster_id, i, p_skill_ids[i]);
    end loop;
  end if;

  return query select child.monster_id, child.in_storage;
end;
$$;

revoke execute on function public.fuse_monsters(uuid, uuid, uuid, bigint, bigint[], jsonb, jsonb, bigint, int) from public, anon, authenticated;
grant execute on function public.fuse_monsters(uuid, uuid, uuid, bigint, bigint[], jsonb, jsonb, bigint, int) to service_role;

-- ---------------------------------------------------------
-- 探索中にできることを絞る: LP の振り分けとフィールドでのアイテム使用は、探索中はできない
-- （編成の入れ替えとリリースは、探索中もできる）
-- ---------------------------------------------------------
create function public.assert_not_exploring(p_owner_id uuid)
returns void
language plpgsql
stable
security definer set search_path = ''
as $$
begin
  if exists (select 1 from public."Expeditions" e where e.owner_id = p_owner_id and e.status = 'exploring') then
    raise exception '探索中はできません';
  end if;
end;
$$;
revoke execute on function public.assert_not_exploring(uuid) from public, anon, authenticated;

create or replace function public.allocate_limit_point(p_monster_id uuid, p_stat text)
returns int
language plpgsql
security definer set search_path = ''
as $$
declare
  uid uuid := auth.uid();
  points int;
  times int;
  cost int;
begin
  if uid is null then
    raise exception 'ログインが必要です';
  end if;
  perform public.assert_not_exploring(uid);
  if p_stat not in ('hp', 'mp', 'atk', 'def', 'int', 'spd') then
    raise exception 'ステータスの指定が不正です: %', p_stat;
  end if;

  select pm.limit_points,
         case p_stat
           when 'hp'  then pm.alloc_hp
           when 'mp'  then pm.alloc_mp
           when 'atk' then pm.alloc_atk
           when 'def' then pm.alloc_def
           when 'int' then pm.alloc_int
           when 'spd' then pm.alloc_spd
         end
    into points, times
    from public."Player_Monsters" pm
   where pm.id = p_monster_id and pm.owner_id = uid
   for update;
  if not found then
    raise exception 'モンスターが見つかりません';
  end if;

  cost := 5 + 5 * (times / 10);
  if points < cost then
    raise exception 'LP が足りません（必要 %、所持 %）', cost, points;
  end if;

  update public."Player_Monsters"
     set limit_points = limit_points - cost,
         alloc_hp  = alloc_hp  + (p_stat = 'hp')::int,
         alloc_mp  = alloc_mp  + (p_stat = 'mp')::int,
         alloc_atk = alloc_atk + (p_stat = 'atk')::int,
         alloc_def = alloc_def + (p_stat = 'def')::int,
         alloc_int = alloc_int + (p_stat = 'int')::int,
         alloc_spd = alloc_spd + (p_stat = 'spd')::int
   where id = p_monster_id;

  return points - cost;
end;
$$;

create or replace function public.use_field_item(p_item_id bigint)
returns void
language plpgsql
security definer set search_path = ''
as $$
declare
  uid uuid := auth.uid();
  item record;
begin
  if uid is null then
    raise exception 'ログインが必要です';
  end if;
  perform public.assert_not_exploring(uid);

  select i.effect_type, i.effect_value, i.usable_in_field into item
    from public."Items" i where i.id = p_item_id;
  if not found then
    raise exception 'アイテムが見つかりません';
  end if;
  if not item.usable_in_field then
    raise exception 'このアイテムはここでは使えません';
  end if;

  perform public.consume_item(uid, p_item_id, 1);

  case item.effect_type
    when 'box_expand' then
      update public.profiles
         set box_capacity = box_capacity + item.effect_value::int
       where id = uid;
    else
      raise exception 'このアイテムはここでは使えません';
  end case;
end;
$$;
