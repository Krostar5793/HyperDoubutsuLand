-- ---------------------------------------------------------
-- 通貨（マスタ）と所持額。基本通貨はペリーカ（P）
-- ---------------------------------------------------------
create table public."Currencies" (
  code text primary key,
  name text not null,
  short_name text not null,
  sort_order int not null default 0
);

insert into public."Currencies" (code, name, short_name, sort_order)
values ('perica', 'ペリーカ', 'P', 1);

create table public."Player_Currencies" (
  owner_id uuid not null references auth.users (id) on delete cascade,
  currency_code text not null references public."Currencies" (code) on update cascade,
  amount bigint not null default 0 check (amount >= 0),
  primary key (owner_id, currency_code)
);

alter table public."Currencies" enable row level security;
create policy "ログインユーザーは通貨を読める"
  on public."Currencies" for select to authenticated using (true);

alter table public."Player_Currencies" enable row level security;
create policy "自分の所持金を読める"
  on public."Player_Currencies" for select to authenticated using (auth.uid() = owner_id);

-- 通貨を渡す（サーバー側専用）。戻り値: 渡した後の額
create function public.grant_currency(p_owner_id uuid, p_currency_code text, p_amount bigint)
returns bigint
language plpgsql
security definer set search_path = ''
as $$
declare
  result bigint;
begin
  if p_amount < 0 then
    raise exception '額が不正です: %', p_amount;
  end if;
  insert into public."Player_Currencies" as pc (owner_id, currency_code, amount)
  values (p_owner_id, p_currency_code, p_amount)
  on conflict (owner_id, currency_code)
  do update set amount = pc.amount + excluded.amount
  returning amount into result;
  return result;
end;
$$;

-- 通貨を使う（サーバー側専用）。戻り値: 残りの額
create function public.spend_currency(p_owner_id uuid, p_currency_code text, p_amount bigint)
returns bigint
language plpgsql
security definer set search_path = ''
as $$
declare
  result bigint;
begin
  if p_amount < 0 then
    raise exception '額が不正です: %', p_amount;
  end if;
  update public."Player_Currencies"
     set amount = amount - p_amount
   where owner_id = p_owner_id and currency_code = p_currency_code and amount >= p_amount
  returning amount into result;
  if not found then
    raise exception '所持金が足りません';
  end if;
  return result;
end;
$$;

revoke execute on function public.grant_currency(uuid, text, bigint) from public, anon, authenticated;
revoke execute on function public.spend_currency(uuid, text, bigint) from public, anon, authenticated;
grant execute on function public.grant_currency(uuid, text, bigint) to service_role;
grant execute on function public.spend_currency(uuid, text, bigint) to service_role;

-- ---------------------------------------------------------
-- エリア（マスタ）
-- ---------------------------------------------------------
create table public."Areas" (
  id bigint generated by default as identity primary key,
  name text not null,
  description text,
  image_path text,
  -- 探索クリア時の報酬
  clear_currency_code text not null default 'perica'
    references public."Currencies" (code) on update cascade,
  clear_amount bigint not null default 0 check (clear_amount >= 0),
  -- 通常戦闘で出現する敵の数（1〜3）
  min_enemies int not null default 1 check (min_enemies between 1 and 3),
  max_enemies int not null default 3 check (max_enemies between 1 and 3),
  is_active boolean not null default true,
  sort_order int not null default 0,
  check (min_enemies <= max_enemies)
);

-- マス: 1 マスごとに、各イベントが起こる確率（%）。合計 100 未満の残りは「何も起きない」
create table public."Area_Squares" (
  area_id bigint not null references public."Areas" (id) on delete cascade,
  position int not null check (position >= 1),
  monster_rate numeric not null default 0 check (monster_rate >= 0),
  item_rate numeric not null default 0 check (item_rate >= 0),
  chest_rate numeric not null default 0 check (chest_rate >= 0),
  choice_rate numeric not null default 0 check (choice_rate >= 0),
  primary key (area_id, position),
  constraint "Area_Squares_rate_total"
    check (monster_rate + item_rate + chest_rate + choice_rate <= 100)
);

-- 通常戦闘で出現するモンスター（重みの比率で抽選。レベルは範囲内でランダム）
create table public."Area_Encounters" (
  id bigint generated by default as identity primary key,
  area_id bigint not null references public."Areas" (id) on delete cascade,
  species_id bigint not null references public."Monster_Species" (id) on delete cascade,
  weight numeric not null default 1 check (weight > 0),
  min_level int not null default 1 check (min_level between 1 and 99),
  max_level int not null default 1 check (max_level between 1 and 99),
  check (min_level <= max_level)
);

-- 落とし物（source = field）と宝箱の中身（source = chest）の候補
create table public."Area_Loot" (
  id bigint generated by default as identity primary key,
  area_id bigint not null references public."Areas" (id) on delete cascade,
  source text not null check (source in ('field', 'chest')),
  item_id bigint references public."Items" (id) on delete cascade,
  currency_code text references public."Currencies" (code) on update cascade on delete cascade,
  weight numeric not null default 1 check (weight > 0),
  min_quantity int not null default 1 check (min_quantity >= 1),
  max_quantity int not null default 1 check (max_quantity >= 1),
  check (min_quantity <= max_quantity),
  -- アイテムか通貨のどちらか一方
  constraint "Area_Loot_item_or_currency"
    check ((item_id is null) <> (currency_code is null))
);

-- ボス（最大 3 体）。仲間にはならない
create table public."Area_Bosses" (
  area_id bigint not null references public."Areas" (id) on delete cascade,
  slot int not null check (slot between 1 and 3),
  species_id bigint not null references public."Monster_Species" (id) on delete cascade,
  level int not null default 1 check (level between 1 and 99),
  primary key (area_id, slot)
);

create index "Area_Encounters_area_idx" on public."Area_Encounters" (area_id);
create index "Area_Loot_area_idx" on public."Area_Loot" (area_id, source);

alter table public."Areas" enable row level security;
create policy "ログインユーザーはエリアを読める"
  on public."Areas" for select to authenticated using (true);
alter table public."Area_Squares" enable row level security;
create policy "ログインユーザーはマスを読める"
  on public."Area_Squares" for select to authenticated using (true);
alter table public."Area_Encounters" enable row level security;
create policy "ログインユーザーは出現モンスターを読める"
  on public."Area_Encounters" for select to authenticated using (true);
alter table public."Area_Loot" enable row level security;
create policy "ログインユーザーは落とし物・宝箱の候補を読める"
  on public."Area_Loot" for select to authenticated using (true);
alter table public."Area_Bosses" enable row level security;
create policy "ログインユーザーはボスを読める"
  on public."Area_Bosses" for select to authenticated using (true);

-- ---------------------------------------------------------
-- 探索の進行状況
--   status: exploring（探索中）/ cleared（クリア）/ failed（全滅）/ retreated（引き返した）
--   position: 進んだマス数（全マスを進むとボス戦）
--   1 人が同時に進められる探索は 1 つだけ
-- ---------------------------------------------------------
create table public."Expeditions" (
  id uuid primary key default gen_random_uuid(),
  owner_id uuid not null references auth.users (id) on delete cascade,
  area_id bigint not null references public."Areas" (id),
  status text not null default 'exploring'
    check (status in ('exploring', 'cleared', 'failed', 'retreated')),
  position int not null default 0 check (position >= 0),
  -- 各マスで起きたことの記録（画面の演出・履歴用）
  log jsonb not null default '[]'::jsonb,
  started_at timestamptz not null default now(),
  ended_at timestamptz
);

create unique index "Expeditions_one_active_per_owner"
  on public."Expeditions" (owner_id) where status = 'exploring';

-- 探索中に拾ったアイテム・通貨（クリア / 引き返しで受け取り、全滅で消える）
create table public."Expedition_Loot" (
  id bigint generated by default as identity primary key,
  expedition_id uuid not null references public."Expeditions" (id) on delete cascade,
  item_id bigint references public."Items" (id),
  currency_code text references public."Currencies" (code) on update cascade,
  quantity bigint not null check (quantity > 0),
  constraint "Expedition_Loot_item_or_currency"
    check ((item_id is null) <> (currency_code is null))
);

create index "Expedition_Loot_expedition_idx" on public."Expedition_Loot" (expedition_id);

alter table public."Expeditions" enable row level security;
create policy "自分の探索を読める"
  on public."Expeditions" for select to authenticated using (auth.uid() = owner_id);

alter table public."Expedition_Loot" enable row level security;
create policy "自分の探索の拾得物を読める"
  on public."Expedition_Loot" for select to authenticated
  using (exists (
    select 1 from public."Expeditions" e
     where e.id = expedition_id and e.owner_id = auth.uid()
  ));

-- ---------------------------------------------------------
-- 探索の 1 マス分の結果を記録する（サーバー側専用）
--   抽選はサーバーの TypeScript（src/lib/game/explore.ts）で行い、結果をここでまとめて保存する
--   p_expected_position が今の position と違えば何もしない（二重送信・同時実行の対策）
--   p_event  : ログに追加する出来事（jsonb）
--   p_loot   : 拾ったもの [{ "item_id": 1, "quantity": 2 } | { "currency_code": "perica", "quantity": 10 }]
--   p_recruit: 仲間になったモンスター { "species_id": 1, "level": 5 }（なければ null）
--   p_finish : null（続く）/ 'cleared' / 'failed' / 'retreated'
-- 戻り値: 仲間になったモンスターの情報など（jsonb）
-- ---------------------------------------------------------
create function public.commit_expedition_step(
  p_expedition_id uuid,
  p_expected_position int,
  p_advance boolean,
  p_event jsonb,
  p_loot jsonb default '[]'::jsonb,
  p_recruit jsonb default null,
  p_finish text default null
)
returns jsonb
language plpgsql
security definer set search_path = ''
as $$
declare
  exp record;
  area record;
  joined record;
  result jsonb := '{}'::jsonb;
  row jsonb;
  loot record;
begin
  if p_finish is not null and p_finish not in ('cleared', 'failed', 'retreated') then
    raise exception '終了状態が不正です: %', p_finish;
  end if;

  select * into exp from public."Expeditions"
   where id = p_expedition_id
   for update;
  if not found then
    raise exception '探索が見つかりません';
  end if;
  if exp.status <> 'exploring' then
    raise exception 'この探索はすでに終わっています';
  end if;
  if exp.position <> p_expected_position then
    raise exception '探索の状態が変わっています。もう一度読み込んでください'
      using errcode = 'P0002';
  end if;

  -- 拾ったもの
  for row in select * from jsonb_array_elements(coalesce(p_loot, '[]'::jsonb)) loop
    insert into public."Expedition_Loot" (expedition_id, item_id, currency_code, quantity)
    values (
      p_expedition_id,
      (row->>'item_id')::bigint,
      row->>'currency_code',
      (row->>'quantity')::bigint
    );
  end loop;

  -- 仲間になったモンスター（全滅しても失われない）
  if p_recruit is not null then
    select * into joined from public.grant_monster(
      exp.owner_id,
      (p_recruit->>'species_id')::bigint,
      (p_recruit->>'level')::int,
      'explore'
    );
    result := result || jsonb_build_object(
      'recruited_monster_id', joined.monster_id,
      'recruited_in_storage', joined.in_storage
    );
  end if;

  update public."Expeditions"
     set position = position + (case when p_advance then 1 else 0 end),
         log = log || jsonb_build_array(p_event),
         status = coalesce(p_finish, status),
         ended_at = case when p_finish is not null then now() else ended_at end
   where id = p_expedition_id;

  -- 終了処理
  if p_finish in ('cleared', 'retreated') then
    for loot in
      select item_id, currency_code, sum(quantity) as quantity
        from public."Expedition_Loot"
       where expedition_id = p_expedition_id
       group by item_id, currency_code
    loop
      if loot.item_id is not null then
        perform public.grant_item(exp.owner_id, loot.item_id, loot.quantity::int);
      else
        perform public.grant_currency(exp.owner_id, loot.currency_code, loot.quantity::bigint);
      end if;
    end loop;
  end if;

  if p_finish = 'cleared' then
    select a.clear_currency_code, a.clear_amount into area
      from public."Areas" a where a.id = exp.area_id;
    if area.clear_amount > 0 then
      perform public.grant_currency(exp.owner_id, area.clear_currency_code, area.clear_amount);
    end if;
    result := result || jsonb_build_object(
      'clear_currency_code', area.clear_currency_code,
      'clear_amount', area.clear_amount
    );
  end if;

  if p_finish = 'failed' then
    delete from public."Expedition_Loot" where expedition_id = p_expedition_id;
  end if;

  return result;
end;
$$;

revoke execute on function public.commit_expedition_step(uuid, int, boolean, jsonb, jsonb, jsonb, text)
  from public, anon, authenticated;
grant execute on function public.commit_expedition_step(uuid, int, boolean, jsonb, jsonb, jsonb, text)
  to service_role;
