-- =========================================================
-- 属性・状態異常と耐性
--   ・モンスターは属性を 1 つ持つ
--   ・属性どうしの相性（すくみ）が、そのモンスターのデフォルトの属性耐性になる
--   ・種族ごとに個別の耐性で上書きできる
--   ・状態異常への耐性は種族ごとに設定する
--   ・設定がない組み合わせは「普通（等倍）」として扱う
-- =========================================================

-- ---------------------------------------------------------
-- 耐性の段階（マスタ）。倍率は Table Editor で調整できる
--   effect = damage  : 倍率をかけたダメージを受ける
--   effect = absorb  : 倍率をかけた量だけ HP が回復する
--   effect = reflect : 倍率をかけたダメージを攻撃側に返す
-- ---------------------------------------------------------
create table public."Resistance_Levels" (
  code text primary key,
  name text not null,
  multiplier numeric not null check (multiplier >= 0),
  effect text not null default 'damage' check (effect in ('damage', 'absorb', 'reflect')),
  sort_order int not null default 0
);

insert into public."Resistance_Levels" (code, name, multiplier, effect, sort_order) values
  ('weak',    '弱点', 2.0, 'damage',  1),
  ('normal',  '普通', 1.0, 'damage',  2),
  ('resist',  '耐性', 0.6, 'damage',  3),
  ('adapt',   '適応', 0.2, 'damage',  4),
  ('immune',  '無効', 0.0, 'damage',  5),
  ('absorb',  '吸収', 1.0, 'absorb',  6),
  ('reflect', '反射', 1.0, 'reflect', 7);

-- ---------------------------------------------------------
-- 属性（マスタ）
-- ---------------------------------------------------------
create table public."Elements" (
  id bigint generated by default as identity primary key,
  name text not null unique,
  description text
);

-- 属性の相性（すくみ）: 攻撃側の属性 → 防御側の属性 の耐性段階
create table public."Element_Matchups" (
  attack_element_id bigint not null references public."Elements" (id) on delete cascade,
  defense_element_id bigint not null references public."Elements" (id) on delete cascade,
  level text not null references public."Resistance_Levels" (code),
  primary key (attack_element_id, defense_element_id)
);

-- モンスター・スキルに属性を持たせる（スキルの属性が NULL なら無属性 = 常に等倍）
alter table public."Monster_Species"
  add column element_id bigint references public."Elements" (id) on delete set null;
alter table public."Skills"
  add column element_id bigint references public."Elements" (id) on delete set null;

-- 種族ごとの属性耐性の上書き（すくみによるデフォルトと違う耐性を持たせたいときだけ登録）
create table public."Species_Element_Resistances" (
  species_id bigint not null references public."Monster_Species" (id) on delete cascade,
  element_id bigint not null references public."Elements" (id) on delete cascade,
  level text not null references public."Resistance_Levels" (code),
  primary key (species_id, element_id)
);

-- ---------------------------------------------------------
-- 状態異常（マスタ）と種族ごとの耐性
-- ---------------------------------------------------------
create table public."Status_Effects" (
  id bigint generated by default as identity primary key,
  name text not null unique,
  description text
);

create table public."Species_Status_Resistances" (
  species_id bigint not null references public."Monster_Species" (id) on delete cascade,
  status_effect_id bigint not null references public."Status_Effects" (id) on delete cascade,
  level text not null references public."Resistance_Levels" (code),
  primary key (species_id, status_effect_id)
);

-- ---------------------------------------------------------
-- RLS: どれもマスタなので、ログインユーザーは読めるが書き込めない
-- ---------------------------------------------------------
alter table public."Resistance_Levels" enable row level security;
create policy "ログインユーザーは耐性段階を読める"
  on public."Resistance_Levels" for select to authenticated using (true);

alter table public."Elements" enable row level security;
create policy "ログインユーザーは属性を読める"
  on public."Elements" for select to authenticated using (true);

alter table public."Element_Matchups" enable row level security;
create policy "ログインユーザーは属性相性を読める"
  on public."Element_Matchups" for select to authenticated using (true);

alter table public."Species_Element_Resistances" enable row level security;
create policy "ログインユーザーは種族の属性耐性を読める"
  on public."Species_Element_Resistances" for select to authenticated using (true);

alter table public."Status_Effects" enable row level security;
create policy "ログインユーザーは状態異常を読める"
  on public."Status_Effects" for select to authenticated using (true);

alter table public."Species_Status_Resistances" enable row level security;
create policy "ログインユーザーは種族の状態異常耐性を読める"
  on public."Species_Status_Resistances" for select to authenticated using (true);

-- ---------------------------------------------------------
-- 実際に適用される属性耐性を求める
--   優先順位: 種族ごとの上書き → 属性の相性（すくみ） → 普通
--   攻撃の属性が NULL（無属性）なら普通
-- 例: select public.element_resistance(1, 3);
-- ---------------------------------------------------------
create function public.element_resistance(p_species_id bigint, p_attack_element_id bigint)
returns text
language sql
stable
set search_path = ''
as $$
  select coalesce(
    (select r.level
       from public."Species_Element_Resistances" r
      where r.species_id = p_species_id
        and r.element_id = p_attack_element_id),
    (select m.level
       from public."Monster_Species" s
       join public."Element_Matchups" m
         on m.defense_element_id = s.element_id
        and m.attack_element_id = p_attack_element_id
      where s.id = p_species_id),
    'normal'
  );
$$;

-- 状態異常への耐性（設定がなければ普通）
create function public.status_resistance(p_species_id bigint, p_status_effect_id bigint)
returns text
language sql
stable
set search_path = ''
as $$
  select coalesce(
    (select r.level
       from public."Species_Status_Resistances" r
      where r.species_id = p_species_id
        and r.status_effect_id = p_status_effect_id),
    'normal'
  );
$$;

grant execute on function public.element_resistance(bigint, bigint) to authenticated;
grant execute on function public.status_resistance(bigint, bigint) to authenticated;
revoke execute on function public.element_resistance(bigint, bigint) from anon;
revoke execute on function public.status_resistance(bigint, bigint) from anon;
